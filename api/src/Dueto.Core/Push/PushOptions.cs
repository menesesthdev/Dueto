using System.Buffers.Text;
using System.ComponentModel.DataAnnotations;
using Dueto.Core.Catalog;

namespace Dueto.Core.Push;

/// <summary>
/// Configuração do Web Push e dos lembretes. Tudo vem de variáveis de ambiente (<c>Push__*</c>).
/// As chaves VAPID são opcionais: sem elas o recurso fica desligado (nenhum push e nenhum lembrete).
/// </summary>
public sealed class PushOptions
{
    public const string SectionName = "Push";

    /// <summary>Atrasos padrão dos lembretes, em minutos: +2 min, +15 min e +1 h.</summary>
    public static readonly int[] DefaultReminderDelaysMinutes = [2, 15, 60];

    /// <summary>Hosts de push service aceitos por padrão (o próprio host ou qualquer subdomínio dele).</summary>
    public static readonly string[] DefaultAllowedEndpointHosts =
    [
        "push.apple.com",
        "fcm.googleapis.com",
        "push.services.mozilla.com",
        "notify.windows.com",
    ];

    /// <summary>Chave pública VAPID (não é segredo; o PWA a usa para assinar o push).</summary>
    public string? VapidPublicKey { get; set; }

    /// <summary>Chave privada VAPID. Segredo: só por variável de ambiente, nunca em log.</summary>
    public string? VapidPrivateKey { get; set; }

    /// <summary>Contato do remetente exigido pelo VAPID: <c>mailto:</c> ou URL https.</summary>
    public string? VapidSubject { get; set; }

    /// <summary>
    /// Atrasos dos reenvios, em minutos. Vazio usa <see cref="DefaultReminderDelaysMinutes"/>
    /// (o binder do .NET somaria um valor padrão de array aos valores configurados).
    /// </summary>
    public int[] ReminderDelaysMinutes { get; set; } = [];

    /// <summary>Hosts de push service aceitos. Vazio usa <see cref="DefaultAllowedEndpointHosts"/>.</summary>
    public string[] AllowedEndpointHosts { get; set; } = [];

    /// <summary>Intervalo entre as varreduras do agendador de lembretes.</summary>
    [Range(1, 3_600)]
    public int SchedulerIntervalSeconds { get; set; } = 15;

    public bool IsConfigured =>
        !string.IsNullOrWhiteSpace(VapidPublicKey) && !string.IsNullOrWhiteSpace(VapidPrivateKey);

    public IReadOnlyList<int> EffectiveReminderDelaysMinutes =>
        ReminderDelaysMinutes.Length > 0 ? ReminderDelaysMinutes : DefaultReminderDelaysMinutes;

    public IReadOnlyList<string> EffectiveAllowedEndpointHosts =>
        AllowedEndpointHosts.Length > 0 ? AllowedEndpointHosts : DefaultAllowedEndpointHosts;

    /// <summary>Regras que o DataAnnotations não cobre. Devolve a mensagem de erro, ou nulo se válido.</summary>
    public string? Validate()
    {
        var hasPublic = !string.IsNullOrWhiteSpace(VapidPublicKey);
        var hasPrivate = !string.IsNullOrWhiteSpace(VapidPrivateKey);
        if (hasPublic != hasPrivate)
        {
            return "Push:VapidPublicKey and Push:VapidPrivateKey must be set together.";
        }

        if (hasPublic && !IsValidSubject(VapidSubject))
        {
            return "Push:VapidSubject must be a mailto: address or an https URL.";
        }

        if (hasPublic && !HasValidVapidKeys())
        {
            return "Push:VapidPublicKey and Push:VapidPrivateKey must be base64url P-256 keys (65 and 32 bytes), as generated by 'npx web-push generate-vapid-keys'.";
        }

        if (ReminderDelaysMinutes.Length > 10 || ReminderDelaysMinutes.Any(d => d is < 1 or > 1_440))
        {
            return "Push:ReminderDelaysMinutes must have at most 10 values between 1 and 1440.";
        }

        if (!AllowedEndpointHosts.All(UrlAllowlist.IsBareHost))
        {
            return "Push:AllowedEndpointHosts must contain bare host names.";
        }

        return null;
    }

    private bool HasValidVapidKeys()
    {
        try
        {
            var publicKey = Base64Url.DecodeFromChars(VapidPublicKey!);
            var privateKey = Base64Url.DecodeFromChars(VapidPrivateKey!);
            return publicKey.Length == 65 && publicKey[0] == 0x04 && privateKey.Length == 32;
        }
        catch (FormatException)
        {
            return false;
        }
    }

    private static bool IsValidSubject(string? subject) =>
        !string.IsNullOrWhiteSpace(subject)
        && (subject.StartsWith("mailto:", StringComparison.OrdinalIgnoreCase)
            || subject.StartsWith("https://", StringComparison.OrdinalIgnoreCase));

    /// <summary>
    /// O servidor envia requisições ao endpoint que o cliente cadastra. Aceitar qualquer URL
    /// permitiria usar a API para chamar hosts internos (SSRF), então só https e hosts da allowlist.
    /// </summary>
    public bool IsAllowedEndpoint(string? endpoint) =>
        UrlAllowlist.IsAllowedHttps(endpoint, EffectiveAllowedEndpointHosts);
}
